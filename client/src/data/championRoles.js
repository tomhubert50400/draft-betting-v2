/**
 * Returns champion names playable in the given role.
 * @param {string} role - One of "Top", "Jungle", "Mid", "Bot", "Support"
 * @returns {string[]} Array of champion names
 */
export function getChampionsForRole(role) {
  return Object.entries(CHAMPION_ROLES)
    .filter(([, roles]) => roles.includes(role))
    .map(([name]) => name);
}

